package com.bailout.stickk.ubi4.coverage

import java.lang.reflect.Modifier
import kotlin.test.Test
import kotlin.test.assertTrue

class Ubi4ClassLoadingSmokeTest {
    @Test
    fun `load and initialize as many UBI4 classes as possible`() {
        var initialized = 0
        var loaded = 0
        ubi4ClassNames.forEach { className ->
            try {
                val clazz = Class.forName(className, true, Thread.currentThread().contextClassLoader)
                loaded++
                val instanceField = clazz.declaredFields.firstOrNull {
                    it.name == "INSTANCE" && Modifier.isStatic(it.modifiers)
                }
                if (instanceField != null) {
                    instanceField.isAccessible = true
                    instanceField.get(null)
                    initialized++
                }
                val ctor = clazz.declaredConstructors.firstOrNull { it.parameterCount == 0 }
                if (ctor != null) {
                    ctor.isAccessible = true
                    ctor.newInstance()
                    initialized++
                }
            } catch (_: Throwable) {
                // best-effort
            }
        }
        assertTrue(loaded > 0, "At least one UBI4 class should be loadable")
        assertTrue(initialized >= 0)
    }

