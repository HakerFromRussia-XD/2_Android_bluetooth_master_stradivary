@testable import MotoricaStart
import XCTest

final class PhoneDialURLFormatterTests: XCTestCase {
    func testDialURL_formatsPhonesAcrossCommonInputs() {
        let cases: [(input: String, expected: String?)] = [
            ("88007077197", "tel:+78007077197"),
            ("8 800 707 71 97", "tel:+78007077197"),
            ("8-800-707-71-97", "tel:+78007077197"),
            ("8 (800) 707-71-97", "tel:+78007077197"),
            ("8(800)7077197", "tel:+78007077197"),
            ("  8 800 707 71 97  ", "tel:+78007077197"),
            ("+7 800 707 71 97", "tel:+78007077197"),
            ("+7 (800) 707-71-97", "tel:+78007077197"),
            ("+7-800-707-71-97", "tel:+78007077197"),
            ("78007077197", "tel:+78007077197"),
            ("7 800 707 71 97", "tel:+78007077197"),
            ("7-800-707-71-97", "tel:+78007077197"),
            ("+78007077197", "tel:+78007077197"),
            ("+7(800)7077197", "tel:+78007077197"),
            ("8 495 123 45 67", "tel:+74951234567"),
            ("8(495)123-45-67", "tel:+74951234567"),
            ("84951234567", "tel:+74951234567"),
            ("7 495 123 45 67", "tel:+74951234567"),
            ("74951234567", "tel:+74951234567"),
            ("+7 495 123 45 67", "tel:+74951234567"),
            ("+7 (495) 123-45-67", "tel:+74951234567"),
            ("8 921 555 12 34", "tel:+79215551234"),
            ("8(921)555-12-34", "tel:+79215551234"),
            ("89215551234", "tel:+79215551234"),
            ("7 921 555 12 34", "tel:+79215551234"),
            ("79215551234", "tel:+79215551234"),
            ("+7 921 555 12 34", "tel:+79215551234"),
            ("+7(921)555-12-34", "tel:+79215551234"),
            ("+1 (415) 555-2671", "tel:+14155552671"),
            ("+44 20 7946 0958", "tel:+442079460958"),
            ("+49 (30) 1234-5678", "tel:+493012345678"),
            ("+34 91 123 45 67", "tel:+34911234567"),
            ("+39 06 6982", "tel:+39066982"),
            ("+86 10 6552 9988", "tel:+861065529988"),
            ("112", "tel:112"),
            ("911", "tel:911"),
            ("02", "tel:02"),
            ("8807077197", nil),
            ("+8807077197", nil),
            ("+880 707 7197", nil)
        ]

        XCTAssertEqual(cases.count, 40)

        for testCase in cases {
            XCTAssertEqual(
                PhoneDialURLFormatter.dialURL(from: testCase.input)?.absoluteString,
                testCase.expected,
                "input: \(testCase.input)"
            )
        }
    }
}
